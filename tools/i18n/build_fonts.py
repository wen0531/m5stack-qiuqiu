#!/usr/bin/env python3
"""Generate one LVGL subset font per language from tools/i18n/strings.json.

Only the glyphs that actually appear in the translations are rasterised, so a
whole language costs a few tens of KB instead of megabytes.

Usage:  python3 tools/i18n/build_fonts.py
"""
import json, subprocess, sys, pathlib

HERE = pathlib.Path(__file__).parent
ROOT = HERE.parent.parent
OUT  = ROOT / "main/assets/fonts"

# Noto Sans CJK is a TTC collection; lv_font_conv cannot read it, so the
# per-script faces are extracted once into a cache directory.
CJK_TTC = "/usr/share/fonts/noto-cjk/NotoSansCJK-Regular.ttc"
CJK_CACHE = pathlib.Path("/tmp/noto-cjk-subsets")
CJK_INDEX = {"SC": 2, "TC": 3, "JP": 0, "KR": 1}

def cjk_font(script: str) -> str:
    """Extract one face from the Noto CJK collection (cached)."""
    out = CJK_CACHE / f"NotoSansCJK-{script}.otf"
    if out.exists():
        return str(out)
    try:
        from fontTools.ttLib import TTCollection
    except ImportError:
        print("fontTools missing: pip install fonttools  (needed for CJK/Japanese/Korean)")
        return ""
    CJK_CACHE.mkdir(parents=True, exist_ok=True)
    TTCollection(CJK_TTC).fonts[CJK_INDEX[script]].save(str(out))
    return str(out)

FONTS = {
    "zh-Hans": lambda: cjk_font("SC"),
    "zh-Hant": lambda: cjk_font("TC"),
    "ja":      lambda: cjk_font("JP"),
    "ko":      lambda: cjk_font("KR"),
    "ru":      lambda: "/usr/share/fonts/TTF/DejaVuSans.ttf",
    "fr":      lambda: "/usr/share/fonts/TTF/DejaVuSans.ttf",
    "de":      lambda: "/usr/share/fonts/TTF/DejaVuSans.ttf",
    "es":      lambda: "/usr/share/fonts/TTF/DejaVuSans.ttf",
    "la":      lambda: "/usr/share/fonts/TTF/DejaVuSans.ttf",
}

SIZE = 26
BPP  = 4

def symbol(name: str) -> str:
    return name.replace("-", "_")

def enum_name(code: str) -> str:
    return code.upper().replace("-", "_")

def emit_cpp(data, langs) -> None:
    """Generate the C++ tables so strings.json stays the only source of truth."""
    gen_dir = ROOT / "main/i18n"
    gen_dir.mkdir(parents=True, exist_ok=True)
    gen_h = gen_dir / "i18n_gen.h"
    gen_inc = gen_dir / "i18n_strings.gen.inc"

    enum_lines = ["// AUTO-GENERATED by tools/i18n/build_fonts.py - do not edit",
                  "#pragma once", "#include <lvgl.h>", "",
                  "enum class Lang : int {"]
    for l in langs:
        enum_lines.append(f"    {enum_name(l)},   /* {l} */")
    enum_lines.append("    COUNT")
    enum_lines.append("};")
    enum_lines.append("")
    for l in langs:
        if l != "en":
            enum_lines.append(f"LV_FONT_DECLARE(i18n_{symbol(l)});")
    gen_h.write_text("\n".join(enum_lines) + "\n")

    entries = []
    for key, tr in data["strings"].items():
        vals = ", ".join('"' + tr.get(l, tr.get("en", "")).replace('"', '\\"') + '"' for l in langs)
        entries.append(f'    {{"{key}", {{{vals}}}}},')
    gen_inc.write_text("\n".join(entries) + "\n")

    # font table + language names, same order as the Lang enum
    fonts = []
    names = []
    for l in langs:
        fonts.append("    &lv_font_montserrat_28," if l == "en" else f"    &i18n_{symbol(l)},")
        names.append('    "' + data["lang_names"].get(l, l) + '",')
    (gen_dir / "i18n_fonts.gen.inc").write_text("\n".join(fonts) + "\n")
    (gen_dir / "i18n_names.gen.inc").write_text("\n".join(names) + "\n")
    (gen_dir / "i18n_codes.gen.inc").write_text("\n".join(f'    "{l}",' for l in langs) + "\n")
    print(f"generated i18n_gen.h + 4 .inc tables ({len(entries)} strings)")

def main() -> int:
    data = json.loads((HERE / "strings.json").read_text())
    langs = [l for l in data["langs"] if l != "en"]
    OUT.mkdir(parents=True, exist_ok=True)

    header = ["// AUTO-GENERATED by tools/i18n/build_fonts.py - do not edit",
              "#pragma once", "#include <lvgl.h>", ""]
    for lang in langs:
        chars = set()
        for entry in data["strings"].values():
            chars.update(entry.get(lang, ""))
        # the language selector shows the language's own name, so it must be in the font too
        chars.update(data.get("lang_names", {}).get(lang, ""))
        # base symbols used by formatting / status lines (space included - a
        # font without U+0020 renders every word as one long placeholder run)
        chars.update(" 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz.:%&-()+/,!?\"'")
        # only strip control characters, never the space
        symbols = "".join(sorted(c for c in chars if c not in "\n\r\t"))

        getter = FONTS.get(lang)
        font = getter() if getter else ""
        if not font or not pathlib.Path(font).exists():
            print(f"ERROR: no font file for {lang}")
            return 1

        out_c = OUT / f"i18n_{symbol(lang)}.c"
        cmd = ["npx", "--yes", "lv_font_conv@1.5.2",
               "--size", str(SIZE), "--bpp", str(BPP), "--format", "lvgl",
               "--font", font, "--symbols", symbols, "--no-compress",
               "--lv-include", "lvgl.h",
               "-o", str(out_c)]
        print(f"[{lang}] {len(symbols)} glyphs -> {out_c.name}")
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            print(r.stderr[-400:])
            return 1
        missing = [ln for ln in r.stderr.splitlines() if "not found" in ln.lower()]
        if missing:
            print(f"ERROR: {lang}: " + "; ".join(missing[:5]))
            return 1
        # strip absolute build paths from the generated comment header
        text = out_c.read_text()
        text = text.replace(str(ROOT) + "/", "")
        out_c.write_text(text)
        header.append(f"LV_FONT_DECLARE(i18n_{symbol(lang)});")

    emit_cpp(data, data["langs"])
    print("done")
    return 0

if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""Generate sim/lv_conf.h from the firmware's sdkconfig.

The device builds LVGL with CONFIG_LV_CONF_SKIP, i.e. every option comes from
Kconfig.  The host build cannot use Kconfig, so this script transcribes the
same options into an lv_conf.h, and only overrides the few settings that must
differ on a PC (memory pool size, log output, OS layer).
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SDKCONFIG = ROOT / "sdkconfig"
OUT = ROOT / "sim" / "lv_conf.h"

# Kconfig "choice" members are value constants inside LVGL, not macros:
# emitting them (e.g. LV_DRAW_SW_ASM_NONE 1) would corrupt the selector values.
CHOICE_PREFIXES = (
    "LV_COLOR_DEPTH_",
    "LV_DRAW_SW_ASM_",
    "LV_OS_",
    "LV_STDLIB_",
    "LV_LOG_LEVEL_",
    "LV_TXT_ENC_",
    "LV_FONT_FMT_TXT_",
    "LV_USE_DRAW_SW_COMPLEX_",
    "LV_DRAW_THREAD_STACK_SIZE_",
)

def is_choice(key: str) -> bool:
    return any(key.startswith(p) for p in CHOICE_PREFIXES)

# host-only overrides: option -> value expression
HOST_OVERRIDES = {
    "LV_MEM_SIZE": "(512 * 1024U)",     # the PC has plenty; keep LVGL heap generous
    "LV_USE_LOG": "1",                  # the device disables logs, the simulator wants them
    "LV_LOG_LEVEL": "LV_LOG_LEVEL_WARN",
    "LV_USE_OS": "LV_OS_NONE",
    "LV_USE_STDLIB_MALLOC": "LV_STDLIB_CLIB",
    "LV_USE_STDLIB_STRING": "LV_STDLIB_CLIB",
    "LV_USE_STDLIB_SPRINTF": "LV_STDLIB_CLIB",
    "LV_USE_DRAW_SW_ASM": "LV_DRAW_SW_ASM_NONE",
    "LV_FONT_DEFAULT": "&lv_font_montserrat_14",
}

def parse_sdkconfig(text):
    on, off, num, string = {}, {}, {}, {}
    for line in text.splitlines():
        m = re.match(r"^(CONFIG_LV_[A-Z0-9_]+)=y$", line)
        if m:
            on[m.group(1)[len("CONFIG_"):]] = 1
            continue
        m = re.match(r"^(CONFIG_LV_[A-Z0-9_]+)=(-?\d+)$", line)
        if m:
            num[m.group(1)[len("CONFIG_"):]] = int(m.group(2))
            continue
        m = re.match(r'^(CONFIG_LV_[A-Z0-9_]+)="(.*)"$', line)
        if m:
            string[m.group(1)[len("CONFIG_"):]] = m.group(2)
            continue
        m = re.match(r"^# CONFIG_LV_[A-Z0-9_]+ is not set$", line)
        if m:
            key = re.search(r"CONFIG_(LV_[A-Z0-9_]+) is not set", line).group(1)
            off[key] = 0
    return on, off, num, string

def main():
    text = SDKCONFIG.read_text()
    on, off, num, string = parse_sdkconfig(text)

    defs = {}
    # Kconfig boolean choices are encoded in the option name itself
    for key in list(on) + list(off):
        m = re.match(r"^(LV_COLOR_DEPTH)_(8|16|24|32)$", key)
        if m:
            defs[m.group(1)] = int(m.group(2)) if on.get(key) else defs.get(m.group(1), 16)

    for k, v in on.items():
        if is_choice(k):
            continue
        defs.setdefault(k, 1)
    for k, v in off.items():
        if is_choice(k):
            continue
        defs.setdefault(k, 0)
    defs.update(num)
    for k, v in string.items():
        defs[k] = f'"{v}"'

    defs.update(HOST_OVERRIDES)
    defs.setdefault("LV_COLOR_DEPTH", 16)

    lines = [
        "/* AUTO-GENERATED by tools/sim/gen_lv_conf.py from sdkconfig - do not edit.",
        " * Regenerate after changing any CONFIG_LV_* option. */",
        "#pragma once",
        "",
    ]
    for k in sorted(defs):
        v = defs[k]
        lines.append(f"#define {k} {v}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(defs)} options, colour depth {defs['LV_COLOR_DEPTH']})")

if __name__ == "__main__":
    sys.exit(main())
